def para_text(p):
    return p.text.strip()


def table_hashes(doc: Document) -> list[str]:
    return [hashlib.sha256(t._tbl.xml.encode("utf-8")).hexdigest() for t in doc.tables]


def count_chars(doc: Document):
    parts = [p.text for p in doc.paragraphs]
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                parts.append(cell.text)
    text = "\n".join(parts)
    return len(re.findall(r"[\u4e00-\u9fff]", text)), len(re.sub(r"\s+", "", text)), text


def section_bounds(doc: Document) -> dict[str, tuple[int, int]]:
    heads = []
    for i, p in enumerate(doc.paragraphs):
        t = para_text(p)
        if p.style.name.startswith("Heading") or re.match(r"^[1-7]\.\d+", t):
            heads.append((i, t))
    bounds = {}
    for idx, (i, t) in enumerate(heads):
        end = heads[idx + 1][0] if idx + 1 < len(heads) else len(doc.paragraphs)
        if t.startswith("5.6"):
            bounds["5.6"] = (i, end)
        for key in ("6.1", "6.2", "6.3", "6.4"):
            if t.startswith(key):
                bounds[key] = (i, end)
    return bounds


def set_para_text(p, text: str) -> None:
    if p.runs:
        p.runs[0].text = text
        for r in p.runs[1:]:
            r.text = ""
    else:
        p.add_run(text)


def replace_section_body(doc: Document, key: str, new_paragraphs: list[str]) -> None:
    start, end = section_bounds(doc)[key]
    body_paras = []
    for i in range(start + 1, end):
        text = para_text(doc.paragraphs[i])
        if not text:
            continue
        if text.startswith(("\u56fe", "\u8868")):
            continue
        body_paras.append(i)
    if len(body_paras) < len(new_paragraphs):
        raise RuntimeError(f"not enough body paragraphs for {key}: {body_paras}")
    for para_idx, new_text in zip(body_paras[: len(new_paragraphs)], new_paragraphs):
        set_para_text(doc.paragraphs[para_idx], new_text)
    for para_idx in body_paras[len(new_paragraphs) :]:
        set_para_text(doc.paragraphs[para_idx], "")


