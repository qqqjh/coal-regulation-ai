"""Run RAGAS metrics for the current RAG method after responses are collected.

Input must be JSONL rows with:
- user_input
- retrieved_contexts
- response
- reference

The skeleton is generated by evaluate_current_rag_method_v1.py. Fill `response`
with the actual v9 review answer for each case before running this script.
"""

from __future__ import annotations

import argparse
import json
import math
import os
from pathlib import Path
from typing import Any


PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_DATASET = PROJECT_ROOT / "rag_eval" / "data" / "current_rag_method_ragas_dataset_skeleton_v1.jsonl"
DEFAULT_OUTPUT = PROJECT_ROOT / "rag_eval" / "data" / "current_rag_method_ragas_metrics_v1.json"
BGE_M3_DIR = PROJECT_ROOT / "models" / "bge-m3"


class LocalBGEM3Embeddings:
    """Minimal LangChain-compatible embedding wrapper around local BGE-M3."""

    def __init__(self, model_dir: Path, batch_size: int = 8, max_length: int = 2048, device: str | None = None):
        self.model_dir = Path(model_dir)
        self.batch_size = batch_size
        self.max_length = max_length
        self.device = device
        self._model = None

    def _ensure_model(self):
        if self._model is not None:
            return
        if not self.model_dir.is_dir():
            raise FileNotFoundError(f"Local BGE-M3 model directory not found: {self.model_dir}")
        os.environ.setdefault("HF_HUB_OFFLINE", "1")
        os.environ.setdefault("TRANSFORMERS_OFFLINE", "1")
        from FlagEmbedding import BGEM3FlagModel
        import torch

        device = self.device or ("cuda" if torch.cuda.is_available() else "cpu")
        self._model = BGEM3FlagModel(
            str(self.model_dir.resolve()),
            normalize_embeddings=True,
            use_fp16=device.startswith("cuda"),
            devices=device,
            batch_size=self.batch_size,
            passage_max_length=self.max_length,
            query_max_length=self.max_length,
            return_dense=True,
            return_sparse=False,
            return_colbert_vecs=False,
        )

    def _embed(self, texts: list[str]) -> list[list[float]]:
        self._ensure_model()
        encoded = self._model.encode(
            texts,
            batch_size=self.batch_size,
            max_length=self.max_length,
            return_dense=True,
            return_sparse=False,
            return_colbert_vecs=False,
        )
        return encoded["dense_vecs"].tolist()

    def embed_documents(self, texts: list[str]) -> list[list[float]]:
        return self._embed(texts)

    def embed_query(self, text: str) -> list[float]:
        return self._embed([text])[0]


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    rows = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def summarize_scores(scores: list[dict[str, Any]]) -> dict[str, Any]:
    keys = sorted({key for row in scores for key in row if key != "user_input"})
    summary: dict[str, Any] = {}
    for key in keys:
        values = []
        for row in scores:
            value = row.get(key)
            if isinstance(value, (int, float)) and not math.isnan(float(value)):
                values.append(float(value))
        if values:
            summary[key] = {
                "mean": sum(values) / len(values),
                "count": len(values),
                "missing_or_failed": len(scores) - len(values),
            }
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--model", default="qwen-plus", help="LangChain chat model name for evaluator LLM.")
    parser.add_argument(
        "--embedding-model",
        default="text-embedding-v4",
        help="OpenAI-compatible embedding model name when --embedding-backend=openai-compatible.",
    )
    parser.add_argument(
        "--embedding-backend",
        choices=["local-bge", "openai-compatible"],
        default="local-bge",
        help="Embedding backend for RAGAS metrics that require embeddings.",
    )
    parser.add_argument(
        "--bge-model-dir",
        type=Path,
        default=BGE_M3_DIR,
        help="Local BGE-M3 model directory when --embedding-backend=local-bge.",
    )
    parser.add_argument(
        "--api-key-env",
        default="DASHSCOPE_API_KEY",
        help="Environment variable containing the evaluator API key.",
    )
    parser.add_argument(
        "--base-url",
        default=os.getenv("DASHSCOPE_BASE_URL", "https://dashscope.aliyuncs.com/compatible-mode/v1"),
        help="OpenAI-compatible evaluator base URL.",
    )
    args = parser.parse_args()

    rows = load_jsonl(args.dataset)
    missing = [row["case_id"] for row in rows if not str(row.get("response", "")).strip()]
    if missing:
        raise SystemExit(
            "RAGAS requires actual model responses. Empty response rows: "
            + ", ".join(missing[:10])
            + (f" ... (+{len(missing) - 10})" if len(missing) > 10 else "")
        )

    try:
        from langchain_openai import ChatOpenAI
        from langchain_openai import OpenAIEmbeddings
        from ragas import EvaluationDataset, evaluate
        from ragas.embeddings import LangchainEmbeddingsWrapper
        from ragas.llms import LangchainLLMWrapper
        try:
            from ragas.metrics.collections import (
                Faithfulness,
                FactualCorrectness,
                LLMContextPrecisionWithReference,
                LLMContextRecall,
                ResponseRelevancy,
            )
        except ImportError:
            from ragas.metrics import (
                Faithfulness,
                FactualCorrectness,
                LLMContextPrecisionWithReference,
                LLMContextRecall,
                ResponseRelevancy,
            )
    except ImportError as exc:
        raise SystemExit(
            "Missing RAGAS dependencies. Install ragas and langchain_openai in this environment first."
        ) from exc

    api_key = os.getenv(args.api_key_env)
    if not api_key:
        raise SystemExit(f"Missing evaluator API key environment variable: {args.api_key_env}")

    # Some RAGAS internals still consult OPENAI_* env vars when a metric lazily
    # constructs helpers. Set them explicitly to the same OpenAI-compatible
    # DashScope endpoint used by the wrappers below.
    os.environ.setdefault("OPENAI_API_KEY", api_key)
    os.environ.setdefault("OPENAI_BASE_URL", args.base_url)

    llm = ChatOpenAI(model=args.model, temperature=0, api_key=api_key, base_url=args.base_url)
    evaluator_llm = LangchainLLMWrapper(llm)
    if args.embedding_backend == "local-bge":
        embeddings = LangchainEmbeddingsWrapper(LocalBGEM3Embeddings(args.bge_model_dir))
    else:
        embeddings = LangchainEmbeddingsWrapper(
            OpenAIEmbeddings(model=args.embedding_model, api_key=api_key, base_url=args.base_url)
        )
    dataset = EvaluationDataset.from_list(rows)
    result = evaluate(
        dataset=dataset,
        metrics=[
            Faithfulness(),
            ResponseRelevancy(),
            LLMContextPrecisionWithReference(),
            LLMContextRecall(),
            FactualCorrectness(),
        ],
        llm=evaluator_llm,
        embeddings=embeddings,
    )
    scores = list(getattr(result, "scores", []))
    payload = {
        "schema": "coal_current_rag_method_ragas_metrics_v1",
        "dataset": str(args.dataset.resolve()),
        "model": args.model,
        "embedding_backend": args.embedding_backend,
        "embedding_model": args.embedding_model,
        "bge_model_dir": str(args.bge_model_dir.resolve()) if args.embedding_backend == "local-bge" else None,
        "metrics": summarize_scores(scores),
        "scores": scores,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(payload, ensure_ascii=False, indent=2))
    print(args.output.resolve())


if __name__ == "__main__":
    main()
